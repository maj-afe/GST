use crate::models::{Customer, SalesInvoice, SalesItem, Item, Batch};
use serde_json::Value;
use sqlx::SqlitePool;
use tauri::State;
use uuid::Uuid;

/// Tally XML endpoint (default Tally port is 9000; spec says localhost:90).
const TALLY_ENDPOINT: &str = "http://localhost:90";
/// Tally company GUID endpoint
#[allow(dead_code)]
const TALLY_COMPANY_GUID: &str = "http://localhost:90";

/// Generates NIC (National Informatics Centre) e-Invoice JSON payload for the
/// Indian GST e-invoicing system.
///
/// This function queries the local database for the invoice and related data,
/// then constructs a JSON payload compliant with the NIC e-Invoice schema
/// (Section 10.1 of the PRD).
///
/// # Arguments
/// * `invoice_id` - The UUID of the sales invoice
/// * `pool` - The SQLite connection pool
///
/// # Returns
/// A JSON string compliant with the NIC e-Invoice schema.
pub async fn generate_e_invoice_json(
    invoice_id: Uuid,
    pool: &SqlitePool,
) -> anyhow::Result<String> {
    // Fetch invoice header
    let invoice: SalesInvoice = sqlx::query_as::<_, SalesInvoice>(
        "SELECT * FROM sales_invoices WHERE id = ?1"
    )
    .bind(invoice_id)
    .fetch_one(pool)
    .await?;

    // Fetch customer
    let customer: Option<Customer> = if let Some(cid) = invoice.customer_id {
        Some(
            sqlx::query_as::<_, Customer>("SELECT * FROM customers WHERE id = ?1")
                .bind(cid)
                .fetch_one(pool)
                .await?,
        )
    } else {
        None
    };

    // Fetch invoice line items with batch and item details
    let sales_items: Vec<SalesItem> = sqlx::query_as::<_, SalesItem>(
        "SELECT * FROM sales_items WHERE invoice_id = ?1"
    )
    .bind(invoice_id)
    .fetch_all(pool)
    .await?;

    // Resolve each line item's batch + item info
    let mut item_lines: Vec<Value> = Vec::new();

    for si in &sales_items {
        let batch: Batch = sqlx::query_as::<_, Batch>("SELECT * FROM batches WHERE id = ?1")
            .bind(si.batch_id)
            .fetch_one(pool)
            .await?;

        let item: Item = sqlx::query_as::<_, Item>("SELECT * FROM items WHERE id = ?1")
            .bind(batch.item_id)
            .fetch_one(pool)
            .await?;

        // Calculate per-item tax (CGST/SGST split for same-state default)
        let taxable = si.total_amount - si.tax_amount;
        let gst_rate = item.gst_rate;
        let half_tax = si.tax_amount / 2.0;

        let line = serde_json::json!({
            "item_no": item_lines.len() + 1,
            "hsn_sac_code": item.hsn_code.unwrap_or_default(),
            "item_name": item.name,
            "description": item.description.unwrap_or_default(),
            "unit": map_unit(&item.unit),
            "quantity": si.quantity,
            "unit_price": si.rate,
            "discount_amount": si.discount_amount,
            "taxable_amount": taxable,
            "cgst_rate": gst_rate / 2.0,
            "sgst_rate": gst_rate / 2.0,
            "igst_rate": 0.0,
            "cgst_amount": half_tax,
            "sgst_amount": half_tax,
            "igst_amount": 0.0,
            "total_amount": si.total_amount,
        });

        item_lines.push(line);
    }

    // Build the seller (pharmacy) info from app settings or fallback
    let seller_name = std::env::var("PHARMA_NAME").unwrap_or_else(|_| "PharmaLocal".to_string());
    let seller_gstin = std::env::var("PHARMA_GSTIN").unwrap_or_default();
    let seller_address = std::env::var("PHARMA_ADDRESS").unwrap_or_default();

    let customer_name = customer.as_ref().map(|c| c.name.clone()).unwrap_or_default();
    let customer_gstin = customer.as_ref().and_then(|c| c.gstin.clone()).unwrap_or_default();
    let customer_address = customer.as_ref().and_then(|c| c.address.clone()).unwrap_or_default();

    let invoice_date = invoice.created_at;

    // Construct NIC e-Invoice JSON (v1.1 schema)
    let e_invoice = serde_json::json!({
        "version": "1.1",
        "profile": "b2b",
        "comment": "Generated by PharmaLocal",
        "primary": {
            "supplier": {
                "legal_name": seller_name,
                "gstin_uin": seller_gstin,
                "address": {
                    "address_line_1": seller_address,
                    "city_name": "NA",
                    "state_code": 29,
                    "country": "IN",
                    "pincode": "000000"
                }
            },
            "customer": {
                "legal_name": customer_name,
                "gstin_uin": customer_gstin,
                "address": {
                    "address_line_1": customer_address,
                    "city_name": "NA",
                    "state_code": 29,
                    "country": "IN",
                    "pincode": "000000"
                }
            },
            "invoice": {
                "invoice_number": invoice.invoice_number,
                "invoice_date": invoice_date.format("%d/%m/%Y").to_string(),
                "invoice_type": "R",
                "supply_type": "I",
                "currency_code": "INR",
                "exchange_rate": 1.0,
                "total_item_count": item_lines.len() as i32,
                "total_document_amount": invoice.total_amount,
                "item_lines": item_lines
            }
        }
    });

    Ok(e_invoice.to_string())
}

/// Pushes invoice data to Tally via Tally XML (Section 10.3 of the PRD).
///
/// Construct Tally-compliant XML and POST it to the Tally server
/// running at http://localhost:90 (or configurable endpoint).
pub async fn push_to_tally(
    invoice_id: Uuid,
    pool: &SqlitePool,
) -> anyhow::Result<()> {
    // Fetch invoice and line items (same as e-invoice generation)
    let invoice: SalesInvoice = sqlx::query_as::<_, SalesInvoice>(
        "SELECT * FROM sales_invoices WHERE id = ?1"
    )
    .bind(invoice_id)
    .fetch_one(pool)
    .await?;

    let sales_items: Vec<SalesItem> = sqlx::query_as::<_, SalesItem>(
        "SELECT * FROM sales_items WHERE invoice_id = ?1"
    )
    .bind(invoice_id)
    .fetch_all(pool)
    .await?;

    // Build Tally XML payload
    let mut tally_xml = String::new();
    tally_xml.push_str(r#"<?xml version="1.0" encoding="UTF-8"?>"#);
    tally_xml.push_str(r#"<?oxygenrng file="TallyUDF_9_220.xml"?>"#);
    tally_xml.push_str("<TALLYMESSAGE xmlns:u=\"TallyUDF_9_220\" xmlns:vu=\"TallyName_9_220\" u:echo=\"false\">");
    tally_xml.push_str("<VOUCHER VOUCHERTYPENAME=\"Invoice\" ACTION=\"Create\">");
    tally_xml.push_str(&format!("<VOUCHERDATE>{}</VOUCHERDATE>", invoice.created_at.format("%d/%m/%Y")));
    tally_xml.push_str(&format!("<VOUCHERNO>{}</VOUCHERNO>", invoice.invoice_number));
    tally_xml.push_str(&format!("<PARTYNAME>{}</PARTYNAME>", invoice.customer_id.unwrap_or_default()));
    tally_xml.push_str(&format!("<AMOUNT>{:.2}</AMOUNT>", invoice.total_amount));

    // Add line items
    tally_xml.push_str("<ALLINVENTORYENTRIES.LIST>");
    for si in &sales_items {
        let batch: Batch = sqlx::query_as::<_, Batch>("SELECT * FROM batches WHERE id = ?1")
            .bind(si.batch_id)
            .fetch_one(pool)
            .await?;
        let item: Item = sqlx::query_as::<_, Item>("SELECT * FROM items WHERE id = ?1")
            .bind(batch.item_id)
            .fetch_one(pool)
            .await?;

        tally_xml.push_str("<INVENTORYENTRY>");
        tally_xml.push_str(&format!("<ITEMNAME>{}</ITEMNAME>", item.name));
        tally_xml.push_str(&format!("<BATCHNO>{}</BATCHNO>", batch.batch_number));
        tally_xml.push_str(&format!("<EXPIRYDATE>{}</EXPIRYDATE>", batch.expiry_date.format("%d/%m/%Y")));
        tally_xml.push_str(&format!("<RATE>{:.2}</RATE>", si.rate));
        tally_xml.push_str(&format!("<QUANTITY>{}</QUANTITY>", si.quantity));
        tally_xml.push_str(&format!("<DISCOUNT>{:.2}</DISCOUNT>", si.discount_amount));
        tally_xml.push_str(&format!("<TAXAMOUNT>{:.2}</TAXAMOUNT>", si.tax_amount));
        tally_xml.push_str(&format!("<AMOUNT>{:.2}</AMOUNT>", si.total_amount));
        tally_xml.push_str("</INVENTORYENTRY>");
    }
    tally_xml.push_str("</ALLINVENTORYENTRIES.LIST>");

    // Add tax details
    tally_xml.push_str("<TAXDETAILS.LIST>");
    tally_xml.push_str("<TAXDETAILS>");
    tally_xml.push_str(&format!("<NAME>CGST</NAME>"));
    tally_xml.push_str(&format!("<RATE>{:.2}</RATE>", invoice.tax_amount / 2.0));
    tally_xml.push_str("</TAXDETAILS>");
    tally_xml.push_str("<TAXDETAILS>");
    tally_xml.push_str(&format!("<NAME>SGST</NAME>"));
    tally_xml.push_str(&format!("<RATE>{:.2}</RATE>", invoice.tax_amount / 2.0));
    tally_xml.push_str("</TAXDETAILS>");
    tally_xml.push_str("</TAXDETAILS.LIST>");

    tally_xml.push_str("</VOUCHER>");
    tally_xml.push_str("</TALLYMESSAGE>");

    // POST to Tally
    let client = reqwest::Client::builder()
        .timeout(std::time::Duration::from_secs(10))
        .build()?;

    let resp = client
        .post(TALLY_ENDPOINT)
        .header("Content-Type", "application/xml")
        .body(tally_xml.clone())
        .send()
        .await?;

    if !resp.status().is_success() {
        return Err(anyhow::anyhow!(
            "Tally push failed with status: {}",
            resp.status()
        ));
    }

    tracing::info!("Successfully pushed invoice {} to Tally", invoice_id);
    Ok(())
}

/// Maps internal unit names to NIC e-invoice unit codes.
fn map_unit(unit: &str) -> &str {
    match unit.to_lowercase().as_str() {
        "strip" | "bottle" | "tablet" | "pack" | "box" |
        "vial" | "tube" | "packet" => "NOS",
        _ => "NOS",
    }
}

/// Tauri command to generate NIC e-invoice JSON.
#[tauri::command]
pub async fn generate_e_invoice_command(
    invoice_id: Uuid,
    state: State<'_, crate::db::DbState>,
) -> Result<String, String> {
    let pool = &state.0;
    generate_e_invoice_json(invoice_id, pool)
        .await
        .map_err(|e| e.to_string())
}

/// Tauri command to push invoice data to Tally.
#[tauri::command]
pub async fn push_to_tally_command(
    invoice_id: Uuid,
    state: State<'_, crate::db::DbState>,
) -> Result<String, String> {
    let pool = &state.0;
    push_to_tally(invoice_id, pool)
        .await
        .map(|_| format!("Pushed invoice {} to Tally", invoice_id))
        .map_err(|e| e.to_string())
}

